  const porId = (id) => CASCOS.find((c) => c.id === id) || null;
  // el mismo modelo en común (los ids terminan en -1-comun, -2-poco-comun, …)
  const comunDe = (c) => {
    const pre = c.id.replace(/-\d-[^/]*$/, "");
    return pre === c.id
      ? null
      : CASCOS.find((x) => x.t === 0 && x.id.replace(/-\d-[^/]*$/, "") === pre) || null;
  };
  const dropDe = (map, tier) => CASCOS.filter((c) => c.drop && c.map === map && c.t === tier);
  const icono = (c) => (c ? '<img src="img/cascos/' + c.file + '" alt="" draggable="false">' : "");
  const imgs = new Map();
  function imagen(c) {
    if (!c) return null;
    let im = imgs.get(c.id);
    if (!im) {
      im = new Image();
      im.src = "img/cascos/" + c.file;
      imgs.set(c.id, im);
    }
    return im;
  }
  function texto(c) {
    const I = window.I18N;
    const t = (k) => (k && I ? I.t(k) : "");
    return { name: t(c.nk), fl: t(c.flk), fx: t(c.fxk) };
  }
  // Pone cualquier casco del catálogo en una pieza. Los que no se dropean se habilitan por acá.
  function aplicar(it, id, fijo) {
    const c = typeof id === "string" ? porId(id) : id;
    if (!c || !it) return it;
    const tx = texto(c);
    const lo = c.def[0],
      hi = c.def[1];
    it.cascoId = c.id;
    it.name = tx.name;
    it.fl = tx.fl || "";
    it.fx = tx.fx || "";
    it.stats = it.stats || {};
    // la defensa sale del modelo en común (mitad de su rango) por la rareza de la pieza, con el mismo azar que el resto
    // del botín: así una rara nunca tiene menos defensa que una común del mismo yelmo
    const b = comunDe(c),
      I = window.INV;
    if (b && I && I.tiradaDef && it.rarity)
      it.stats.def = Math.max(
        1,
        Math.round(((b.def[0] + b.def[1]) / 2) * I.tiradaDef(it.rarity, fijo, it.oleada)),
      );
    else it.stats.def = fijo ? hi : lo + Math.floor(Math.random() * (hi - lo + 1));
    return it;
  }
  return { MAPS, CASCOS, porId, dropDe, icono, imagen, texto, aplicar };
